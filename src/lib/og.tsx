import { readFile } from 'node:fs/promises'
import { join } from 'node:path'

import { ImageResponse } from 'next/og'

import { routing } from '@/i18n/routing'
import type { PageKey } from '@/lib/metadata'
import ar from '../../messages/ar.json'
import de from '../../messages/de.json'
import en from '../../messages/en.json'

/**
 * Shared renderer for every opengraph-image / twitter-image route.
 * 1200×630: midnight background, blue accent, "Novusfy" in Nexa Heavy, the
 * localized page headline (meta.<page>.ogTitle) and novusfy.com.
 *
 * Arabic: satori (next/og) joins Arabic letters but has no bidi/RTL layout —
 * word spacing breaks up and mixed lines such as the slogan ("Next الخاص بك
 * يبدأ الآن.") come out in the wrong word order. So /ar uses the English card;
 * its alt text stays Arabic.
 *
 * satori cannot parse variable fonts, so the mono face is a static instance
 * from assets/fonts/og/ (generated by scripts/build-web-fonts.py).
 */
export const OG_SIZE = { width: 1200, height: 630 }
export const OG_CONTENT_TYPE = 'image/png'

const MIDNIGHT = '#0A0A0F'
const BLUE = '#0106FF'
const BLUE_TINT = '#333DFF'

/** Locale whose strings go on the card (Arabic falls back to English, see above). */
const cardLocale = (locale: string) => (locale === 'ar' ? routing.defaultLocale : locale)

/** Eyebrow label above the headline: the page's footer label (home: the tagline). */
const LABEL_KEY: Record<PageKey, 'tagline' | 'about' | 'expertise' | 'consultation' | 'learning' | 'contact'> = {
  home: 'tagline',
  about: 'about',
  expertise: 'expertise',
  consultation: 'consultation',
  learning: 'learning',
  contact: 'contact',
}

const asset = (...p: string[]) => readFile(join(process.cwd(), ...p))

/**
 * Strings are read from messages/*.json directly: image metadata is generated
 * at build time, outside a request, where next-intl's getTranslations() would
 * read request headers and fail the build.
 */
const MESSAGES = { en, de, ar }
function strings(locale: string, page: PageKey) {
  const m = MESSAGES[locale as keyof typeof MESSAGES] ?? en
  return { ogTitle: m.meta[page].ogTitle, label: m.footer[LABEL_KEY[page]] }
}

/** For generateImageMetadata: one image per route, with localized alt text. */
export async function ogImageMetadata(
  params: Promise<{ locale: string }> | { locale: string },
  page: PageKey,
) {
  const { locale } = await params
  return [
    {
      id: 'card',
      alt: `Novusfy — ${strings(locale, page).ogTitle}`,
      size: OG_SIZE,
      contentType: OG_CONTENT_TYPE,
    },
  ]
}

export async function renderOgImage(params: Promise<{ locale: string }>, page: PageKey) {
  const locale = cardLocale((await params).locale)
  const { ogTitle: headline, label } = strings(locale, page)
  const [nexa, mono, icon] = await Promise.all([
    asset('assets/fonts/Nexa-Heavy.ttf'),
    asset('assets/fonts/og/JetBrainsMono-Regular.ttf'),
    asset('public/icon-white.png'),
  ])

  return new ImageResponse(
    (
      <div
        style={{
          width: '100%',
          height: '100%',
          display: 'flex',
          flexDirection: 'column',
          justifyContent: 'space-between',
          padding: '64px 72px',
          backgroundColor: MIDNIGHT,
          backgroundImage: `radial-gradient(circle at 92% 8%, rgba(1,6,255,0.55), rgba(1,6,255,0) 52%)`,
          color: '#FFFFFF',
        }}
      >
        {/* Brand: mark + wordmark */}
        <div style={{ display: 'flex', alignItems: 'center', gap: 18 }}>
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img
            src={`data:image/png;base64,${icon.toString('base64')}`}
            width={52}
            height={53}
            alt=""
          />
          <div style={{ fontFamily: 'Nexa', fontSize: 46, letterSpacing: -1.5 }}>Novusfy</div>
        </div>

        {/* Label + headline */}
        <div style={{ display: 'flex', flexDirection: 'column', gap: 26 }}>
          <div
            style={{
              display: 'flex',
              alignItems: 'center',
              gap: 14,
              fontFamily: 'JetBrains Mono',
              fontSize: 24,
              letterSpacing: 3,
              textTransform: 'uppercase',
              color: '#A9AEFF',
            }}
          >
            <div style={{ width: 12, height: 12, borderRadius: 6, backgroundColor: BLUE_TINT }} />
            {label}
          </div>
          <div
            style={{
              fontFamily: 'Nexa',
              fontSize: headline.length > 30 ? 74 : 86,
              lineHeight: 1.04,
              letterSpacing: -2.5,
              maxWidth: 1000,
            }}
          >
            {headline}
          </div>
        </div>

        {/* Stitch divider + domain */}
        <div style={{ display: 'flex', flexDirection: 'column', gap: 26 }}>
          <div style={{ display: 'flex', borderTop: '2px dashed rgba(255,255,255,0.22)' }} />
          <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between' }}>
            <div style={{ fontFamily: 'JetBrains Mono', fontSize: 26, color: 'rgba(255,255,255,0.78)' }}>
              novusfy.com
            </div>
            <div style={{ display: 'flex', width: 140, height: 10, borderRadius: 5, backgroundColor: BLUE }} />
          </div>
        </div>
      </div>
    ),
    {
      ...OG_SIZE,
      fonts: [
        { name: 'Nexa', data: nexa, weight: 900, style: 'normal' },
        { name: 'JetBrains Mono', data: mono, weight: 400, style: 'normal' },
      ],
    },
  )
}
